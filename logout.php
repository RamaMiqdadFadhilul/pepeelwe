<?php

include_once("bootstrap.php");


/*
|--------------------------------------------------------------------------
| Start session
|--------------------------------------------------------------------------
*/

if (
    session_status() ===
    PHP_SESSION_NONE
) {
    session_start();
}


/*
|--------------------------------------------------------------------------
| Catat logout
|--------------------------------------------------------------------------
*/

if (isset($_SESSION['user'])) {

    Log::catat(
        "LOGOUT",
        [
            "email" =>
                $_SESSION['user']['email']
        ]
    );
}


/*
|--------------------------------------------------------------------------
| Hapus session
|--------------------------------------------------------------------------
*/

$_SESSION = [];

session_destroy();


/*
|--------------------------------------------------------------------------
| Kembali ke login
|--------------------------------------------------------------------------
*/

header(
    "Location: login.php"
);

exit();